import io
import sympy as sp

def to_markdown(r):
    lines = [
        "# Symbolic Function Explorer — Analysis",
        f"**Input:** `{r['source']}`",
        f"**Simplified:** `{sp.sstr(r['expression'])}`",
        f"**Derivative:** `{sp.sstr(r['derivative'])}`",
        f"**Indefinite integral:** `{sp.sstr(r['integral'])}`",
        f"**Real roots:** {r['roots_display']}",
        f"**Domain:** {r['domain']}",
        f"**Parity:** {r['parity']}",
        f"**Singular points:** {r['singular_points']}",
        "", "## Critical points", "| x | f(x) | Classification |", "|---|---|---|"
    ]
    lines += [f"| {p['x']} | {p['f(x)']} | {p['classification']} |" for p in r["critical_points"]]
    lines += ["", "## Limits", "| Location | Limit |", "|---|---|"]
    lines += [f"| {p['Location']} | {p['Limit']} |" for p in r["limits"]]
    lines += ["", "## Explanations"]
    for item in r["explanations"]:
        lines += [f"### {item['title']}", item["steps"], "", item["summary"], ""]
    lines += ["---", "Generated by SFE. Educational use; verify results independently."]
    return "\n".join(lines)

def to_pdf(r):
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
        from reportlab.lib.styles import getSampleStyleSheet
    except ImportError:
        raise
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=letter)
    styles = getSampleStyleSheet()
    story = [Paragraph("Symbolic Function Explorer — Analysis", styles["Title"]), Spacer(1, 12)]
    content = [
        f"Input: {r['source']}", f"Simplified: {sp.sstr(r['expression'])}",
        f"Derivative: {sp.sstr(r['derivative'])}", f"Integral: {sp.sstr(r['integral'])}",
        f"Real roots: {r['roots_display']}", f"Domain: {r['domain']}", f"Parity: {r['parity']}",
        f"Singular points: {r['singular_points']}", "Critical points:"
    ]
    content += [f"{p['x']}: {p['f(x)']} — {p['classification']}" for p in r["critical_points"]]
    content += ["Limits:"] + [f"{p['Location']}: {p['Limit']}" for p in r["limits"]]
    for item in r["explanations"]:
        content += [item["title"], item["steps"].replace("\n", " "), item["summary"]]
    for line in content:
        story.append(Paragraph(str(line).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"), styles["BodyText"]))
        story.append(Spacer(1, 6))
    doc.build(story)
    return buffer.getvalue()
